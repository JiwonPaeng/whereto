-- 계열을 7개에서 3개로 줄인다. 마스터 데이터를 실제로 작성해 보니 수험생이
-- 실제로 쓰는 구분(문과/이과/예체능)에 수렴했다. 사범계 학과는 과목에 따라
-- 인문(국어교육)과 자연(수학교육)으로, 체육교육은 예체능으로 자연히 갈린다.
--
-- ⚠️ 이 데이터는 §11.2 공식 홈페이지 대조를 완전히 거치지 않았다.
-- 클로즈드 테스트용이며, 오픈 베타 전에 재검수가 필요하다.

-- ── 1. 계열 3분류 ─────────────────────────────────────────────────────────
alter table programs drop constraint programs_faculty_group_check;
alter table programs add constraint programs_faculty_group_check
  check (faculty_group in ('인문', '자연', '예체능'));

alter table profiles drop constraint profiles_track_check;
update profiles set track = case track
  when '사회' then '인문'
  when '공학' then '자연'
  when '의약' then '자연'
  when '사범' then '인문'   -- 사범은 3분류에 대응이 없다. 재선택을 유도한다.
  else track
end
where track in ('사회', '공학', '의약', '사범');
alter table profiles add constraint profiles_track_check
  check (track in ('인문', '자연', '예체능'));

